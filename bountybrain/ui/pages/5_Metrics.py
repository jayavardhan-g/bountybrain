"""Metrics: graph structure, coverage, and evaluation results."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

import pandas as pd
import streamlit as st

from bountybrain.config import settings

st.set_page_config(page_title="Metrics — BountyBrain", page_icon="📊", layout="wide")
st.title("📊 Metrics")
st.caption("Everything on this page is regenerated by `build_graph.py` and `eval.py`.")


def load(name: str) -> dict | None:
    path = Path(settings.artifact_dir) / name
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return None


graph = load("graph_metrics.json")
retrieval = load("eval_retrieval.json")
classification = load("eval_classification.json")
planner = load("eval_planner.json")

tab_graph, tab_retr, tab_clf, tab_plan = st.tabs(
    ["Knowledge graph", "Retrieval", "Classification", "Recon planner"]
)

with tab_graph:
    if not graph:
        st.warning("Run `python build_graph.py` to generate graph metrics.")
    else:
        s = graph["structure"]
        cols = st.columns(5)
        cols[0].metric("Nodes", f"{s['nodes']:,}")
        cols[1].metric("Edges", f"{s['edges']:,}")
        cols[2].metric("Mean degree", s["mean_degree"])
        cols[3].metric("Components", f"{s['connected_components']:,}")
        cols[4].metric("Largest component", f"{s['largest_component_share']:.1%}")

        c1, c2 = st.columns(2)
        c1.subheader("Nodes by type")
        c1.bar_chart(pd.Series(s["node_kinds"]).sort_values(ascending=False))
        c2.subheader("Edges by type")
        c2.bar_chart(pd.Series(s["edge_kinds"]).sort_values(ascending=False))

        st.subheader("Weakness coverage")
        cov = graph["coverage"]
        st.caption(
            "What fraction of the 969 CWE classes is backed by each kind of evidence. "
            "'Any document' is near-100% by construction — every CWE has its own "
            "catalogue page — so the external-evidence rows are the meaningful ones."
        )
        st.dataframe(
            pd.DataFrame(
                [
                    {"backed by": label, "count": cov[key], "share": f"{cov[key + '_pct']:.1%}"}
                    for label, key in [
                        ("attack pattern (CAPEC)", "with_attack_pattern"),
                        ("detection signature (nuclei)", "with_detection_signature"),
                        ("disclosed writeup", "with_disclosed_writeup"),
                        ("external document", "with_external_document"),
                        ("observed CVE", "with_observed_cve"),
                        ("VRT payout priority", "with_vrt_priority"),
                    ]
                ]
            ),
            hide_index=True,
            width="stretch",
        )

        hier = graph.get("hierarchy") or {}
        if hier:
            st.subheader("CWE taxonomy shape")
            hc = st.columns(4)
            hc[0].metric("ChildOf edges", f"{hier.get('childof_edges', 0):,}")
            hc[1].metric("Roots (pillars)", hier.get("roots", 0))
            hc[2].metric("Max depth", hier.get("max_depth", 0))
            hc[3].metric("Mean depth", hier.get("mean_depth", 0))

        corpus = graph.get("corpus") or {}
        if corpus.get("writeups_by_year"):
            st.subheader("Disclosed writeups by year")
            st.bar_chart(pd.Series(corpus["writeups_by_year"]))

        econ = graph.get("economics") or {}
        if econ.get("top_by_mean_bounty"):
            st.subheader(
                f"Best-paying weakness classes (≥{econ['min_paid_threshold']} paid writeups)"
            )
            st.dataframe(
                pd.DataFrame(econ["top_by_mean_bounty"]), hide_index=True, width="stretch"
            )

with tab_retr:
    if not retrieval:
        st.warning("Run `python eval.py --retrieval`.")
    else:
        st.caption(
            f"{retrieval.get('queries', 0)} held-out queries. Each arm sees the same "
            "queries and the same corpus."
        )
        # Each row already carries its own `mode`; transposing and resetting the
        # index would try to insert a second one and crash the page.
        st.dataframe(
            pd.DataFrame(list(retrieval["modes"].values())),
            hide_index=True,
            width="stretch",
        )
        if retrieval.get("by_doc_type"):
            st.subheader(f"By document type ({retrieval.get('breakdown_mode')})")
            st.dataframe(
                pd.DataFrame(retrieval["by_doc_type"]).T.reset_index(names="doc_type"),
                hide_index=True,
                width="stretch",
            )

with tab_clf:
    if not classification:
        st.warning("Run `python eval.py --classification`.")
    else:
        for set_name, per_method in classification.get("sets", {}).items():
            st.subheader(f"Gold set: {set_name}")
            st.dataframe(
                pd.DataFrame(per_method).T.reset_index(names="strategy"),
                hide_index=True,
                width="stretch",
            )

with tab_plan:
    if not planner:
        st.warning("Run `python eval.py --planner`.")
    elif "error" in planner:
        st.error(planner["error"])
    else:
        st.caption(
            f"{planner['cases']} held-out cases across {planner['products']} products. "
            "Held-out templates are excluded from the evidence pool, so the planner "
            "cannot score the fact it is being graded on."
        )
        st.dataframe(
            pd.DataFrame(planner["strategies"]).T.reset_index(names="strategy"),
            hide_index=True,
            width="stretch",
        )
